# ---------------------------------------------------------------------------
# issue #10: a default value must determine the selected anyOf-branch
# ---------------------------------------------------------------------------

# schema as generated by pydantic for ``other_default: Union[str, int] = 1``
schema_issue_10 = {
    'title': 'Other Default',
    'default': 1,
    'anyOf': [{'type': 'string'}, {'type': 'integer'}],
}


def test_any_of_default_selects_matching_branch(qtbot):
    """default=1 matches the integer-branch -> the integer-widget must be selected."""
    builder = WidgetBuilder({})
    widget = AnyOfSchemaWidget(schema_issue_10, {}, builder)
    widget.state = 1

    assert widget.select_combo.currentIndex() == 1
    assert widget.state == 1


def test_any_of_default_fills_every_branch(qtbot):
    """a list of defaults fills each branch and leaves the first branch selected."""
    builder = WidgetBuilder({})
    widget = AnyOfSchemaWidget(schema_issue_10, {}, builder)
    widget.state = ['hello', 5]

    assert widget.select_combo.currentIndex() == 0
    assert [w.state for w in widget.widgets] == ['hello', 5]


def test_any_of_unmatched_default_does_not_crash(qtbot):
    """a default matching none of the branches must not raise."""
    builder = WidgetBuilder({})
    widget = AnyOfSchemaWidget(schema_issue_10, {}, builder)
    widget.state = 1.5

    assert widget.select_combo.currentIndex() == 0


schema_issue_10_object = {
    'default': {'a': 1},
    'anyOf': [
        {'type': 'object', 'properties': {'a': {'type': 'integer'}}},
        {'type': 'object', 'properties': {'b': {'type': 'string'}}},
    ],
}


def test_any_of_object_default_selects_matching_branch(qtbot):
    """an object-default must select the branch that declares all its keys."""
    builder = WidgetBuilder({})
    widget = AnyOfSchemaWidget(schema_issue_10_object, {}, builder)
    widget.state = {'a': 1}

    assert widget.select_combo.currentIndex() == 0
    assert widget.state == {'a': 1}
